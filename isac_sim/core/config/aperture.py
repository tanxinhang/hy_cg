"""接收阵列：给 DD 感知模型增加角度维。"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Aperture:
    """接收阵列：给 DD 感知模型加上**角度**这一维。

    已发布的模型只有 DD，而角度探针（``ANGULAR_IDENTIFIABILITY_PROBE.md``）
    量出了这件事的代价：单阵元时**典型**的逐链路逃逸比是 ``4.1e-04``，
    也就是说共享同一个时延-多普勒格的目标根本不可分，整个"可辨识性"叙事的关键
    在于接收机得有一个空间维。

    本段把这一维加到**生产**数字真正会用到的地方：时延-多普勒碰撞惩罚
    （``model.build_base_gains``）。目前落在同一个 DD 格里的两个目标会完全互相
    遮蔽，于是链路的回波功率被"同格目标数"除。有了阵列，这一对改由
    ``|A(delta_u)|^2`` 遮蔽 —— 单阵元时它等于 ``1``，随着两者在角度上分开而
    变小 —— 于是惩罚变成一个**软**计数，在 ``m_rx = 1`` 时精确退化为今天的
    整数计数。

    **本段有意不做的事。** 它不加阵列的收集增益（期望回波上的 ``10 log10 m``）。
    那是链路预算量，效果上与 ``radar_net_gain_db`` 无法区分，把它折进来会让任何
    实测提升在"更有选择性"与"单纯更响"之间变得含糊。见
    :mod:`isac_sim.sensing.aperture`。

    ``enable`` 默认 ``False``、``m_rx`` 默认 ``1``：门关着时每个已发布数字逐位不变。
    """

    enable: bool = False
    # 半波长 ULA 的接收阵元数。1 == 已发布的纯 DD 模型。
    m_rx: int = 1
    # 一维阵列所分辨的机体系轴（0 = x，1 = y）。固定，不拟合：一维阵列只分辨
    # 一个轴，而且有前后模糊，所以"哪个轴更好"是 oracle 选择，本模型不允许做。
    axis: int = 0
